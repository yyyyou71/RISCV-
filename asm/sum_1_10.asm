# ==========================================================================
# sum_1_10.asm —— 求 1+2+...+10，然后在程序内部"自检"结果是不是 55
#
# 两个关键点（和以前的手写版不同）：
#
#   1) 用【标签】而不是裸偏移 -12
#      GNU as 会把裸数字当成"绝对地址"，不是相对偏移。
#      写 loop: 标签，让汇编器替你算偏移，改代码也不用重算。
#
#   2) 【程序内自检】
#      TB 不用再手算 gpr[1] 该等于几，只查 x31 一个寄存器：
#          gpr[31] == 1  → 全部检查通过
#          gpr[31] == 0  → 有检查没过（gpr[30] 里是失败项数）
# ==========================================================================

        .text                   # 下面放代码段
        .globl _start           # 把 _start 导出成入口符号

# ---- 寄存器分工 ----
#   x1  = sum 累加器
#   x2  = i
#   x3  = 循环剩余次数
#   x4  = 临时存期望值
#   x30 = 出错计数（0 = 全对）
#   x31 = 最终结论（1 = PASS，0 = FAIL）

_start:
        addi x30, x0, 0         # 出错计数清零

        # ========== 被测程序：sum(1..10) ==========
        addi x1, x0, 0          # sum = 0
        addi x2, x0, 0          # i   = 0
        addi x3, x0, 10         # n   = 10
loop:                           # ← 标签：循环入口
        addi x2, x2, 1          #   i = i + 1
        add  x1, x1, x2         #   sum = sum + i
        addi x3, x3, -1         #   n = n - 1
        bne  x0, x3, loop       #   n != 0 就回去（偏移由汇编器算）

        # ========== 自检：sum 应该等于 55 ==========
        addi x4, x0, 55         # 期望值，手算一次
        beq  x1, x4, chk_done   # 相等 → 跳过
        addi x30, x30, 1        # 不相等 → 出错计数 +1
chk_done:

        # ========== 汇总结论 ==========
        beq  x30, x0, pass      # 0 个错误 → pass
        addi x31, x0, 0         # FAIL
        jal  x0, halt
pass:
        addi x31, x0, 1         # PASS
halt:
        jal  x0, halt           # 原地自旋，等 TB 采样
