# ==========================================================================
# asm/start.s —— 启动桩
#
# 【为什么需要它】
#   复位后 PC = 0，CPU 从地址 0 开始执行。
#   而 C 的 main 是个普通函数，它只「用」环境，不「建」环境：
#       main 第一句是   addi sp,sp,-16    ← 假设 sp 已经有效
#       main 最后一句是 jr ra             ← 需要 ra 里有返回地址
#   所以必须有一小段代码，在 main 之前把这些准备好。
#   它只能是汇编，而且不能依赖任何东西 —— 因为 C 代码本身就需要栈。
#
# 【它做的四件事】
#   1. 设 sp        —— 让 main 有栈可用
#   2. call main    —— 跳进去执行，顺便把返回地址存进 ra
#   3. 报告返回值   —— 写内存映射外设 tohost，TB 看到就结束仿真
#   4. 自旋         —— 让 PC 停下来，等 TB 采样
#
# 【注意】本文件必须排在命令行【第一个】，它才会落在地址 0：
#       ./build.sh program/c_main.hex asm/start.s c/main.c
# ==========================================================================

        .equ    TOHOST, 0x00030000   # ★ 必须和 Acore.v 里 sel_dev 的窗口一致

        .text                   # 指示符：下面进代码段
        .globl  _start          # 把 _start 导出成全局符号
                                #   build.sh 里的 -e _start 就靠它找到入口

_start:                         # 标签：地址 0 就在这里
        la sp, _stack_top       # ① 设栈指针
                                #   值来自 link.ld：_stack_top = 0x00020000
                                #   也就是 RAM 窗口 (0x10000~0x1FFFF) 顶端之外一格
                                #   低 4 位是 0 → 满足 16 字节对齐的 ABI 约定
                                #   栈向【低地址】生长，永远不会碰到 0x20000 本身
                                #   展开后：auipc sp,0x20 ; mv sp,sp（PC 相对，位置无关）

        call    main            # ② 调用 C 的 main
                                #   伪指令 → auipc + jalr（PC 相对寻址）
                                #   ★ 它自动把「下一条指令的地址」存进 ra
                                #     这就是 main 结尾 jr ra 能返回的原因

        li      t0, TOHOST      # ③ 报告退出码：写内存映射外设 tohost
                                #   ★ TOHOST 必须和 Acore.v 里 sel_dev 的窗口一致
                                #   展开后只有 1 条：lui t0, 0x30
        sw      a0, 0(t0)       #   a0 = main 的返回值（0 失败 / 1 通过）
                                #   TB 看到这拍 dev_we 就取出 a0 当退出码，
                                #   然后 $finish —— 不用再数时钟拍数了

                                #   （原来这里还有一条 mv x31,a0 当"哨兵"给 TB 看，
                                #     现在删掉了：TB 以前得猜"最后一次写 x31 是哪条
                                #     指令"，而 sort.c 的 merge 会拿 t6(=x31) 当临时
                                #     寄存器，非常脆弱。结果由 tohost 主动交出，不再需要）

        

halt:                           # ④ 死循环
        j       halt            #   跳到自己的地址 → 偏移量 0 → 原地打转
                                #   没有它的话 PC 会一路 +4 走进 ROM 的 NOP 区，
                                #   仿真跑很久，而且 TB 采样时状态早变了
