"""Generate fixed boot self-check answers; no C division-by-zero is evaluated."""
import sys
from pathlib import Path
PROJECT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(PROJECT/'tests'))
from m_reference import result
PAIRS=[(0,0),(1,0),(0xffffffff,0),(0x80000000,0),(0x80000000,0xffffffff),
       (0x80000000,1),(0xffffffff,0xffffffff),(0xffffffff,2),(7,0xfffffffd),
       (0xfffffff9,3),(0xfffffff9,0xfffffffd),(0x7fffffff,0x80000000),
       (0x80000000,0x80000000),(0x12345678,0x87654321),(0xffffffff,0x7fffffff),(0x10000,0x10000)]
def main():
    text='/* Generated by scripts/generate_m_boot_vectors.py. */\n'
    text+='static const uint32_t m_vectors[][10] = {\n'
    for a,b in PAIRS:
        text+='    {'+', '.join(f'0x{x:08x}u' for x in [a,b]+[result(op,a,b) for op in range(8)])+'},\n'
    text+='};\n'
    (PROJECT/'firmware/coremark_port/m_boot_vectors.h').write_text(text,encoding='ascii')
if __name__=='__main__': main()
