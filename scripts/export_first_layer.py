"""Extract the real first W8A16 layer for a small board integration checkpoint.

No network inference or RTL simulation. The full model stays outside Git.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

ROOT=Path(__file__).resolve().parents[1]


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model',type=Path,default=ROOT/'build/integration-review/model_prepared/model.bin')
    args=parser.parse_args()
    data=args.model.read_bytes();h=struct.unpack_from('<16I',data)
    if h[:5]!=(0x314d4941,2,64,64,99) or h[13]!=1:
        raise ValueError('Expected the prepared 99-task W8A16 model')
    task=struct.unpack_from('<16I',data,h[5]-h[6])
    if (task[0],task[6],task[7],task[8],task[9],task[10],task[11],task[12])!=(1,0x600060,0x200003,91,6,48,48,0):
        raise ValueError('Unexpected first-layer topology; review before changing hardware test')
    regions=[('weight',task[2],32*9*16),('bias',task[3],32*4),('quant',task[5],32*32)]
    payload=b'';offsets={}
    for name,address,size in regions:
        if address<h[6] or address+size>h[12]:raise ValueError('Asset outside model readonly region')
        chunk=data[address-h[6]:address-h[6]+size]
        if len(chunk)!=size:raise ValueError('Truncated model asset')
        offsets[name]=len(payload);payload+=chunk
    values=struct.unpack('<%dI'%(len(payload)//4),payload)
    lines=['/* Generated by scripts/export_first_layer.py; first real model layer only. */',
           '#ifndef AI_FIRST_LAYER_ASSETS_H','#define AI_FIRST_LAYER_ASSETS_H','#include <stdint.h>',
           '#define FL_ASSET_BYTES %du'%len(payload),
           '#define FL_BIAS_WORD %du'%(offsets['bias']//4),
           '#define FL_QUANT_WORD %du'%(offsets['quant']//4),
           'static const uint32_t fl_assets[%d]={'%len(values)]
    for i in range(0,len(values),8):lines.append('    '+','.join('0x%08xu'%v for v in values[i:i+8])+',')
    lines+=['};','#endif','']
    (ROOT/'firmware/ai_first_layer_assets.h').write_text('\n'.join(lines))
    report=dict(scope='First of 99 tasks; actual model weights, bias and Q13 quantization',
                model_sha256=hashlib.sha256(data).hexdigest(),asset_sha256=hashlib.sha256(payload).hexdigest(),
                asset_bytes=len(payload),offsets=offsets,input_shape=[96,96,3],output_shape=[48,48,32],
                input_layout='HWC, align16 channels, INT16',full_network=False)
    (ROOT/'reports/preprocess/first_layer_assets.json').write_text(json.dumps(report,indent=2)+'\n')
    print('First layer:',len(payload),'asset bytes, 96x96x3 -> 48x48x32; no inference run')


if __name__=='__main__':main()
